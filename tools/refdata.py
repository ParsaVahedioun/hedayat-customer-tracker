def parse_customer_code(code):
    """THE single source of truth for parsing a customer code (left -> right).

    A code is only positional-parsed when it is a well-formed 10-digit account
    code. Anything else (e.g. the six-digit '21xxxx' legacy numbers) is
    reported as invalid rather than being half-parsed into a fake region.
    """
    c = str(code if code is not None else "").strip()
    valid = len(c) == 10 and c.isdigit()
    if not valid:
        return {
            "code": c,
            "valid": False,
            "customerTypeCode": "",
            "customerType": "نامشخص",
            "regionCode": "",
            "regionName": "نامشخص",
            "serial": "",
        }
    return {
        "code": c,
        "valid": True,
        "customerTypeCode": c[0:2],
        "customerType": CUSTOMER_TYPES.get(c[0:2], "نامشخص"),
        "regionCode": c[4:6],
        "regionName": REGION_CODES.get(c[4:6], "نامشخص"),
        "serial": c[6:10],
    }
